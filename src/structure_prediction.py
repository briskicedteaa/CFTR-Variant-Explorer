def validate_protein_sequence(sequence):
    """Validate and clean a protein sequence."""
    sequence = sequence.strip().upper().replace(" ", "").replace("\n", "")

    valid_amino_acids = set("ACDEFGHIKLMNPQRSTVWY")

    if not sequence:
        raise ValueError("Protein sequence is empty.")

    invalid = set(sequence) - valid_amino_acids

    if invalid:
        raise ValueError(
            f"Invalid amino-acid characters found: {', '.join(sorted(invalid))}"
        )

    return sequence


def create_mutated_sequence(
    human_sequence,
    position,
    wild_type,
    mutated_type
):
    """Create a mutated protein sequence from a CFTR position."""
    sequence = validate_protein_sequence(human_sequence)

    position = int(position)

    if position < 1 or position > len(sequence):
        raise ValueError("Variant position is outside the CFTR sequence.")

    if sequence[position - 1] != wild_type:
        raise ValueError(
            f"Wild-type mismatch at position {position}: "
            f"expected {sequence[position - 1]}, got {wild_type}"
        )

    sequence = (
        sequence[:position - 1]
        + mutated_type
        + sequence[position:]
    )

    return sequence


from pathlib import Path

from colabfold.batch import get_queries, run, set_model_type
from colabfold.download import download_alphafold_params


def run_structure_prediction(
    sequence,
    jobname="CFTR_variant",
):
    """Run a lightweight ColabFold prediction for one CFTR variant."""

    sequence = validate_protein_sequence(sequence)

    output_dir = Path("structure_results") / jobname
    output_dir.mkdir(parents=True, exist_ok=True)

    query_file = output_dir / f"{jobname}.fasta"

    with open(query_file, "w") as f:
        f.write(f">{jobname}\n")
        f.write(f"{sequence}\n")

    queries, is_complex = get_queries(str(query_file))

    model_type = set_model_type(
        is_complex,
        "alphafold2_ptm"
    )

data_dir = Path("colabfold_data")
data_dir.mkdir(parents=True, exist_ok=True)

download_alphafold_params(
    model_type,
    data_dir
)

results = run(
    queries=queries,
    result_dir=str(output_dir),
    use_templates=False,
    custom_template_path=None,
    num_relax=0,
    msa_mode="mmseqs2_uniref_env",
    model_type=model_type,
    num_models=1,
    num_recycles=3,
    is_complex=is_complex,
    data_dir=data_dir,
    keep_existing_results=True,
    rank_by="auto",
    user_agent="CFTR-Variant-Explorer",
)

return results
    
import glob


def find_pdb_file(output_dir):
    """Find the predicted PDB structure generated by ColabFold."""
    pdb_files = sorted(
        glob.glob(
            f"{output_dir}/**/*.pdb",
            recursive=True
        )
    )

    if not pdb_files:
        raise FileNotFoundError(
            "No predicted PDB structure was found."
        )

    return pdb_files[0]
import py3Dmol

def create_structure_view(pdb_file, color_mode="confidence"):
    """Create an interactive 3D view of a predicted protein structure."""

    view = py3Dmol.view(width=800, height=600)

    with open(pdb_file, "r") as f:
        pdb_data = f.read()

    view.addModel(pdb_data, "pdb")

    if color_mode == "confidence":
        view.setStyle({
            "cartoon": {
                "colorscheme": {
                    "prop": "b",
                    "gradient": "roygb",
                    "min": 50,
                    "max": 90
                }
            }
        })

    elif color_mode == "n_to_c":
        view.setStyle({
            "cartoon": {
                "color": "spectrum"
            }
        })
    else:
        raise ValueError(
            "color_mode must be 'confidence' or 'n_to_c'."
        )
    view.zoomTo()
    return view


def find_prediction_pdb(output_dir):
    """Find the first predicted PDB file in the output directory."""
    output_dir = Path(output_dir)

    pdb_files = list(output_dir.glob("*.pdb"))

    if not pdb_files:
        return None

    return pdb_files[0]