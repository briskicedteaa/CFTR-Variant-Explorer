def validate_protein_sequence(sequence):
    """Validate and clean a protein sequence."""
    sequence = sequence.strip().upper().replace(" ", "").replace("\n", "")

    valid_amino_acids = set("ACDEFGHIKLMNPQRSTVWY")

    if not sequence:
        raise ValueError("Protein sequence is empty.")

    invalid = set(sequence) - valid_amino_acids

    if invalid:
        raise ValueError(
            f"Invalid amino-acid characters found: {', '.join(sorted(invalid))}"
        )

    return sequence


def prepare_colabfold_query(sequence, query_name="CFTR_variant"):
    """Prepare a validated protein sequence for a ColabFold query."""
    sequence = validate_protein_sequence(sequence)

    return {
        "name": query_name,
        "sequence": sequence,
    }
    
from pathlib import Path
import os
from colabfold.batch import get_queries, run, set_model_type
from colabfold.utils import setup_logging

def run_structure_prediction(
    sequence,
    jobname="CFTR_variant",
    msa_mode="mmseqs2_uniref_env",
    model_type="alphafold2_ptm",
    num_models=5,
    num_recycles=3,
):

    """Run ColabFold structure prediction for one protein sequence."""

    sequence = validate_protein_sequence(sequence)

    output_dir = Path("structure_results") / jobname
    output_dir.mkdir(parents=True, exist_ok=True)

    queries_path = output_dir / f"{jobname}.csv"

    with open(queries_path, "w") as f:
        f.write(f"id,sequence\n{jobname},{sequence}")

    setup_logging(
        output_dir / "log.txt"
    )

    queries, is_complex = get_queries(
        str(queries_path)
    )

    model_type = set_model_type(

        is_complex,
        model_type
    )

    download_alphafold_params(
        model_type,
        Path(".")
    )

    results = run(
        queries=queries,
        result_dir=str(output_dir),
        use_templates=False,
        custom_template_path=None,
        num_relax=0,
        msa_mode=msa_mode,
        model_type=model_type,
        num_models=num_models,
        num_recycles=num_recycles,
        is_complex=is_complex,
        data_dir=Path("."),
        keep_existing_results=True,
        rank_by="auto",
        pair_mode="unpaired_paired",
        stop_at_score=100.0,
        user_agent="colabfold/google-colab-main",
    )

    return results
    
import glob


def find_pdb_file(output_dir):
    """Find the predicted PDB structure generated by ColabFold."""
    pdb_files = sorted(
        glob.glob(
            f"{output_dir}/**/*.pdb",
            recursive=True
        )
    )

    if not pdb_files:
        raise FileNotFoundError(
            "No predicted PDB structure was found."
        )

    return pdb_files[0]
import py3Dmol

def create_structure_view(pdb_file, color_mode="confidence"):
    """Create an interactive 3D view of a predicted protein structure."""

    view = py3Dmol.view(width=800, height=600)

    with open(pdb_file, "r") as f:
        pdb_data = f.read()

    view.addModel(pdb_data, "pdb")

    if color_mode == "confidence":
        view.setStyle({
            "cartoon": {
                "colorscheme": {
                    "prop": "b",
                    "gradient": "roygb",
                    "min": 50,
                    "max": 90
                }
            }
        })

    elif color_mode == "n_to_c":
        view.setStyle({
            "cartoon": {
                "color": "spectrum"
            }
        })

    else:
        raise ValueError(
            "color_mode must be 'confidence' or 'n_to_c'."
        )

    view.zoomTo()

    return view